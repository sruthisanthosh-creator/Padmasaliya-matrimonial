let currentLang = 'en';

function getPath(obj, path){
  return path.split('.').reduce((o,k)=> (o&&o[k]!==undefined)?o[k]:null, obj);
}

function applyLang(lang){
  currentLang = lang;
  try{ localStorage.setItem('padma_lang', lang); }catch(e){}
  document.documentElement.lang = lang;
  document.body.style.fontFamily = lang==='ta' ? "'Noto Sans Tamil', var(--font-body)" : lang==='te' ? "'Noto Sans Telugu', var(--font-body)" : "var(--font-body)";
  const dict = translations[lang];
  document.querySelectorAll('[data-i18n]').forEach(el=>{
    const key = el.getAttribute('data-i18n');
    const val = getPath(dict, key);
    if(val!==null) el.innerHTML = val;
  });
  document.querySelectorAll('[data-i18n-placeholder]').forEach(el=>{
    const key = el.getAttribute('data-i18n-placeholder');
    const val = getPath(dict, key);
    if(val!==null) el.setAttribute('placeholder', val);
  });
  const label = lang==='en' ? 'English' : lang==='ta' ? 'தமிழ்' : 'తెలుగు';
  document.querySelectorAll('[data-i18n-lang-label]').forEach(el=> el.textContent = label);

  // language card selection state on screen 1
  document.querySelectorAll('.lang-card').forEach(c=>{
    c.classList.toggle('selected', c.getAttribute('data-lang')===lang);
  });
  // dropdown selected state
  document.querySelectorAll('.lang-dd-menu button').forEach(b=>{
    b.classList.toggle('sel', b.getAttribute('data-lang')===lang);
  });
}

